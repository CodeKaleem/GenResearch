def redate_commits(date_map):
    env_filter = "#!/bin/sh\n"
    for short_hash, new_date in date_map.items():
        env_filter += f"""
if git log --pretty=format:"%h" | grep -q "^{short_hash}"; then
    if [ "$GIT_COMMIT" = "$(git rev-parse {short_hash} 2>/dev/null)" ]; then
        export GIT_AUTHOR_DATE="{new_date}"
        export GIT_COMMITTER_DATE="{new_date}"
    fi
fi
"""
    return env_filter

